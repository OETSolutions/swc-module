#!/usr/bin/env python3
"""Prove N-62's PINNED CA behaves like a pin, not a bundle: the release fetch
ACCEPTS a host whose CA it pins and REJECTS one whose CA it does not.

**Why this is the check that matters.** N-62's defect was that the code said
"pinned CA" while using IDF's ~200-root default bundle. A bundle and a pin are
indistinguishable by a SUCCESSFUL fetch -- both accept the real release host. They
differ on a host whose CA is in the bundle but not pinned: a bundle accepts it, a
pin refuses. So the discriminating test is a REJECT.

**The two runs, on the DUT, against a Cloudflare quick tunnel (its chain is
Cloudflare/SSL.com, NOT the Sectigo root GitHub uses):**

  REJECT  build with the RELEASE pin (`Update/ReleaseCa.h`, Sectigo root E46 --
          the shipped anchor) but the manifest URL pointed at the tunnel. The old
          bundle would ACCEPT the tunnel (Cloudflare is one of its ~200 roots);
          the pin must REFUSE it -> `/api/ota/check` reports the manifest could not
          be read (a TLS failure).
  ACCEPT  build with `-D SWC_BENCH_RELEASE_CA` pinning the TUNNEL's own root
          (generated by `tools/gen_bench_ca.py`). Now the pin matches, so the fetch
          succeeds -> `/api/ota/check` reports an update is available.

Together they show the anchor is a single CA: it refuses a public host it does not
pin and accepts one it does.

**This flashes the DUT twice** (one build per pin), so it is slow (~20 min). It
leaves the DUT on the ACCEPT image; reflash the production image afterwards.

Usage:
  python3 tools/bench_pin_ca.py

Exit codes: 0 both behaviours held, 1 a check failed (a real defect), 2 env.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bench_ladder import Dut                      # noqa: E402
import bench_prov                                 # noqa: E402
import bench_wifi_upload as wu                    # noqa: E402
import bench_ota_release as bor                   # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def build_and_flash(port, manifest_url, bench_ca_dir, outdir):
    env = dict(os.environ)
    env["SWC_FW_VERSION"] = "0.8.0"
    env["SWC_GIT_SHA"] = "benchpin"
    env["PLATFORMIO_BUILD_DIR"] = outdir
    flags = f'-D SWC_BENCH_MANIFEST_URL=\\"{manifest_url}\\"'
    if bench_ca_dir is not None:
        # Point the include search at the generated bench CA header and select it.
        flags += f" -D SWC_BENCH_RELEASE_CA -I{bench_ca_dir}"
    env["PLATFORMIO_BUILD_FLAGS"] = flags
    print(f"== building DUT image (manifest {manifest_url}, "
          f"{'pinned to the TUNNEL CA (accept)' if bench_ca_dir else 'pinned to the RELEASE CA (reject)'})")
    r = subprocess.run(["pio", "run", "-e", "esp32s3"], cwd=REPO, env=env,
                       capture_output=True, text=True, timeout=900)
    if r.returncode != 0:
        print(r.stdout[-2500:], file=sys.stderr)
        print(r.stderr[-2000:], file=sys.stderr)
        return False
    img = os.path.join(outdir, "esp32s3", "firmware.bin")
    if not os.path.exists(img):
        print("ERROR: no image built", file=sys.stderr)
        return False
    r = subprocess.run([sys.executable, os.path.join(REPO, "tools", "dev_push_ota.py"),
                        "--port", port, "--image", img],
                       capture_output=True, text=True, timeout=1200)
    print("   " + "\n   ".join((r.stdout or "").splitlines()[-2:]))
    return r.returncode == 0


def run_check(port, ssid, passphrase, esp_prov):
    """Open the window, provision, and return the /api/ota/check body text."""
    dut = Dut(port)
    try:
        dut.collect(0.4)
        opened = wu.open_window(dut)
        if not opened:
            return None, None
        ble, pop, token = opened
        time.sleep(4)
        rc, out = bench_prov.run_esp_prov(esp_prov, "SWC-" + ble, pop, ssid,
                                          passphrase, timeout=180)
        if "WiFi state: Connected" not in bench_prov.strip_ansi(out):
            print(bench_prov.strip_ansi(out)[-300:], file=sys.stderr)
            return None, None
        ip = wu.arp_ip_for_mac(wu.station_mac(ble)) or wu.DEFAULT_LAN_IP
        for _ in range(40):
            _, body = bor.http_post(ip, "/api/ota/check", token, timeout=8)
            if body:
                return token, body.decode("utf-8", "replace")
            time.sleep(1)
        return token, None
    finally:
        try:
            dut.request(type="maintenance_exit", timeout=2.0)
        except Exception:
            pass
        dut.close()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--port", default="/dev/cu.usbmodem1234561")
    ap.add_argument("--ssid", default=None)
    ap.add_argument("--passphrase", default=None)
    args = ap.parse_args()

    ssid = args.ssid or wu.env_value("WIFI_SSID")
    passphrase = args.passphrase if args.passphrase is not None else wu.env_value("WIFI_PASSWORD")
    esp_prov = bench_prov.find_esp_prov()
    if not ssid or passphrase is None or esp_prov is None:
        print("ERROR: need WIFI_SSID/WIFI_PASSWORD in code/.env and esp_prov.py.",
              file=sys.stderr)
        return 2

    workdir = tempfile.mkdtemp(prefix="swc_pin_")
    docroot = os.path.join(workdir, "www")
    os.makedirs(docroot)
    server = bor.ReleaseServer(docroot, workdir)
    failed = False
    try:
        server.start()
        print(f"release host: {server.url}")
        served = bor.build_image(os.path.join(workdir, "served"), bor.NEW_VERSION, "benchpin")
        if served is None:
            return 1
        size, sha = bor.stage_release(docroot, server.url, served)
        if not server.reachable("/version_manifest.json"):
            print("ERROR: the tunnel is not serving the manifest.", file=sys.stderr)
            return 2
        host = server.url.split("//", 1)[1]
        manifest_url = server.url + "/version_manifest.json"

        # Generate the tunnel's OWN root CA as a bench pin.
        benchca = os.path.join(workdir, "benchca")
        if subprocess.run([sys.executable, os.path.join(REPO, "tools", "gen_bench_ca.py"),
                           host, benchca], capture_output=True).returncode != 0:
            print("ERROR: could not generate the bench CA.", file=sys.stderr)
            return 2

        # --- REJECT: release pin (Sectigo/GitHub) vs a Cloudflare host ------
        if not build_and_flash(args.port, manifest_url, None, os.path.join(workdir, "rej")):
            return 1
        time.sleep(3)
        _, body = run_check(args.port, ssid, passphrase, esp_prov)
        rejected = body is not None and "could not be read" in body
        print(f"\nREJECT: /api/ota/check -> {body!r}")
        print(f"   the release pin REFUSED a host it does not pin -> "
              f"{'PASS (the anchor is a PIN, not a bundle)' if rejected else 'FAIL'}")
        if body is not None and "update is available" in body:
            print("   FAIL: the bundle accepted a public CA it should not have -- "
                  "the anchor is NOT pinned (N-62 regression).", file=sys.stderr)
        failed |= not rejected

        # --- ACCEPT: pin the tunnel's own CA --------------------------------
        if not build_and_flash(args.port, manifest_url, benchca, os.path.join(workdir, "acc")):
            return 1
        time.sleep(3)
        _, body = run_check(args.port, ssid, passphrase, esp_prov)
        accepted = body is not None and "update is available" in body
        print(f"\nACCEPT: /api/ota/check -> {body!r}")
        print(f"   the pin ACCEPTED the host it pins -> "
              f"{'PASS' if accepted else 'FAIL'}")
        failed |= not accepted
    finally:
        server.stop()

    print("\n" + ("FAIL: see the step above." if failed else
                  "PASS: N-62 -- the release fetch's trust anchor is a real PIN: it "
                  "accepts the host it pins and refuses one it does not."))
    print("NOTE: the DUT is left on the ACCEPT (bench) image; reflash the "
          "production image.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
